// Builds two plain SQL files from the Prisma migrations, for databases where the Prisma command
// line cannot connect (the Rust engine often cannot reach Supabase from home networks).
// Paste a file into the Supabase SQL editor and run it.
//
//   node scripts/build-manual-sql.mjs
//
//   prisma/manual/upgrade-existing-database.sql   a database that already has the schema.
//                                                 Safe to run more than once.
//   prisma/manual/fresh-database.sql              an empty database: the first migration plus the upgrade.
//
// Migrations 20260902000000 and 20260903000000 are left out of both. They repeat tables the first
// migration already creates, which is why `prisma migrate` stops on an empty database.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const migrations = path.join(here, '..', 'prisma', 'migrations');
const outDir = path.join(here, '..', 'prisma', 'manual');
fs.mkdirSync(outDir, { recursive: true });

const INIT = '20260830000000_init_schema';
const DUPLICATES = new Set(['20260902000000_deltaflow_atlas', '20260903000000_api_keys']);

const names = fs.readdirSync(migrations, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();
const read = (n) => fs.readFileSync(path.join(migrations, n, 'migration.sql'), 'utf8').trim();
const block = (n) => `-- ── ${n} ${'─'.repeat(Math.max(3, 70 - n.length))}\n${read(n)}\n`;

const newer = names.filter((n) => n !== INIT && !DUPLICATES.has(n));

const header = (title, body) =>
  `-- ${title}\n-- Generated by scripts/build-manual-sql.mjs. Do not edit by hand.\n${body.map((l) => `-- ${l}`).join('\n')}\n\n`;

fs.writeFileSync(
  path.join(outDir, 'upgrade-existing-database.sql'),
  header('Upgrade an existing WasteChainMapper database', [
    'Run in the Supabase SQL editor. Every statement is safe to run again.',
    `Contains: ${newer.join(', ')}`,
  ]) + newer.map(block).join('\n'),
);

fs.writeFileSync(
  path.join(outDir, 'fresh-database.sql'),
  header('Create the WasteChainMapper schema in an EMPTY database', [
    'Run once in the Supabase SQL editor, on a database with no tables yet.',
    'On a database that already has the tables, run upgrade-existing-database.sql instead.',
    `Contains: ${[INIT, ...newer].join(', ')}`,
  ]) + [INIT, ...newer].map(block).join('\n'),
);

console.log('wrote prisma/manual/upgrade-existing-database.sql and fresh-database.sql');
console.log('newer migrations included:', newer.join(', '));
